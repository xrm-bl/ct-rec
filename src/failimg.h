static int	FailGlyph(int c)
{
	const char	*p;

	c = toupper(c);
	if ((p = strchr(fail_font_chars, c)) == NULL || c == '\0')
		return (int)strlen(fail_font_chars) - 1;	/* blank */
	return (int)(p - fail_font_chars);
}

/* Fill img (W*H, row-major) with bg and draw nlines strings in fg, centred,
   using the largest integer scale at which the longest line fits. */
static void	FailImageText(float *img, int W, int H, float fg, float bg,
			      const char **lines, int nlines)
{
	int	i, l, maxlen = 1, scale, sx, sy, th, y0;
	size_t	n;

	for (n = 0; n < (size_t)W * (size_t)H; n++) img[n] = bg;
	for (l = 0; l < nlines; l++)
	    if ((int)strlen(lines[l]) > maxlen) maxlen = (int)strlen(lines[l]);

	sx = (W * 9 / 10) / (FAIL_CELL_W * maxlen);
	sy = (H * 9 / 10) / (FAIL_CELL_H * nlines);
	scale = (sx < sy) ? sx : sy;
	if (scale < 1) scale = 1;

	th = nlines * FAIL_CELL_H * scale;
	y0 = (H - th) / 2;
	if (y0 < 0) y0 = 0;

	for (l = 0; l < nlines; l++) {
	    const char	*s = lines[l];
	    int		len = (int)strlen(s),
			x0 = (W - len * FAIL_CELL_W * scale) / 2,
			yl = y0 + l * FAIL_CELL_H * scale;

	    if (x0 < 0) x0 = 0;
	    for (i = 0; i < len; i++) {
		const unsigned char	*g = fail_font[FailGlyph(s[i])];
		int	r, c, xc = x0 + i * FAIL_CELL_W * scale;

		for (r = 0; r < FAIL_FONT_H; r++)
		    for (c = 0; c < FAIL_FONT_W; c++)
			if (g[r] & (1 << (FAIL_FONT_W - 1 - c))) {
			    int	x, y,
				xs = xc + c * scale,
				ys = yl + (r + 1) * scale;	/* 1 blank row above */

			    for (y = ys; y < ys + scale && y < H; y++)
				for (x = xs; x < xs + scale && x < W; x++)
				    if (x >= 0 && y >= 0)
					img[(size_t)y * (size_t)W + (size_t)x] = fg;
			}
	    }
	}
}

