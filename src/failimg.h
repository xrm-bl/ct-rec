/* failimg.h - placeholder slice for a failed reconstruction.            */
/*                                                                      */
/* When every projection of a slice is judged black (no X-rays), ct_rec */
/* and ofct_rec write, under the normal output name, an image with the   */
/* file name, "fail!" and the reason drawn in a 5x7 bitmap font scaled  */
/* to the image size, so that the failure is visible in any viewer and   */
/* the slice numbering of the stack stays complete.  The exit status is  */
/* still non-zero and the ImageDescription carries "FAILED: ...".       */
/*                                                                      */
/* Generated by gen_failimg.py; the font covers A-Z 0-9 . ! : - _ / ( ) = */
/* and space; lower-case letters are drawn as upper case, anything else  */
/* as a blank.                                                          */
/*----------------------------------------------------------------------*/
